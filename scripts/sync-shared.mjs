// Copies the page's pure coach code into server/src/shared/, so the server rebuilds the same
// facts and prompts the page would (CC-130). The server builds without the page's sources, and
// its modules need `.js` in relative imports, so the copies are rewritten to match. Run
// `npm run sync:shared` after changing any file in the closure; tests/unit/shared-sync.test.ts
// fails on a stale copy. Never edit server/src/shared/ by hand.
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = resolve(root, "src");
const out = resolve(root, "server/src/shared");

/** The files the server uses; everything they import is copied too. */
export const ENTRIES = ["src/coach/call.ts"];

const IMPORT = /^(\s*(?:import|export)[^;]*?from\s+["'])(\.[^"']+)(["'])/gm;

function resolveImport(from, spec) {
  const base = resolve(dirname(from), spec);
  for (const c of [`${base}.ts`, `${base}/index.ts`]) if (existsSync(c)) return c;
  throw new Error(`${relative(root, from)} imports ${spec}, which is not a .ts file`);
}

/** The generated files: path under server/src/shared/ -> text. */
export function build() {
  const files = new Map();
  const visit = (file) => {
    const rel = relative(src, file);
    if (rel.startsWith("..")) throw new Error(`${file} is outside src/`);
    if (files.has(rel)) return;
    const text = readFileSync(file, "utf8");
    files.set(rel, "");
    const rewritten = text.replace(IMPORT, (_, a, spec, q) => {
      visit(resolveImport(file, spec));
      return `${a}${spec}.js${q}`;
    });
    if (/\b(?:document|window|localStorage|navigator)\b/.test(text.replace(/\/\/.*$/gm, ""))) {
      throw new Error(`${rel} touches the DOM, so the server can't share it`);
    }
    files.set(
      rel,
      `// GENERATED by scripts/sync-shared.mjs from src/${rel}. Do not edit; run \`npm run sync:shared\`.\n${rewritten}`,
    );
  };
  for (const e of ENTRIES) visit(resolve(root, e));
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = build();
  rmSync(out, { recursive: true, force: true });
  for (const [rel, text] of files) {
    const dest = resolve(out, rel);
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, text);
  }
  console.warn(`server/src/shared: ${files.size} files`);
}
